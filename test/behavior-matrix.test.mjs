// Drives the real token helper and identity script against a temp config, one case per row
// of the credential/identity behavior matrix in docs/design/per-owner-identity-and-credential.md,
// plus the owner-absent and owner-unresolvable cases that must never fall back.
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tokenScript = path.join(root, "src", "multi-account-token.mjs");
const identityScript = path.join(root, "src", "identity.mjs");

const agentIdentity = { login: "example-agent", displayName: "Example Agent", footerHost: "example-host" };

function pat(tokenPath) {
  return { type: "pat", tokenPath };
}

// `gh` stand-in that reports a fixed acting login, as `gh auth status` would.
function ghStub(dir, login) {
  const file = path.join(dir, `gh-${login.replace(/\W/g, "_")}`);

  fs.writeFileSync(file, `#!/bin/sh\necho "  ✓ Logged in to github.com account ${login} (keyring)"\n`, { mode: 0o755 });

  return file;
}

function fixture(buildAccounts, { defaultAccount = "default-org", actingLogin = "example-agent[bot]" } = {}) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "behavior-matrix-"));
  const tokenFile = (name) => {
    const file = path.join(dir, `${name}.token`);

    fs.writeFileSync(file, `github_pat_${name}`, { mode: 0o600 });

    return file;
  };
  const configPath = path.join(dir, "config.json");

  fs.writeFileSync(
    configPath,
    JSON.stringify({ defaultAccount, accounts: buildAccounts(tokenFile) }),
    { mode: 0o600 }
  );

  const env = { ...process.env, HOME: dir, IDENTITY_ROUTER_CONFIG: configPath, AGENT_IDENTITY_GH_BIN: ghStub(dir, actingLogin) };

  delete env.GH_REPO;
  delete env.IDENTITY_ROUTER_ORG;

  const run = (script, args, extraEnv = {}) =>
    spawnSync(process.execPath, [script, ...args], { cwd: dir, env: { ...env, ...extraEnv }, encoding: "utf8" });

  return {
    dir,
    token: (owner) => run(tokenScript, owner ? ["--repo", `${owner}/repo`] : []),
    footer: (owner, extraEnv = {}) => run(identityScript, ["--footer"], { ...(owner ? { GH_REPO: `${owner}/repo` } : {}), ...extraEnv }),
    check: (owner) => run(identityScript, ["--check"], owner ? { GH_REPO: `${owner}/repo` } : {})
  };
}

const matrixAccounts = (tokenFile) => ({
  "default-org": { accountId: 1, targetType: "organization", credential: pat(tokenFile("default-org")), identity: agentIdentity },
  "both-org": { accountId: 2, targetType: "organization", credential: pat(tokenFile("both-org")), identity: agentIdentity },
  "cred-org": { accountId: 3, targetType: "organization", credential: pat(tokenFile("cred-org")) },
  "ident-org": { accountId: 4, targetType: "organization", identity: agentIdentity }
});

test("credential + identity: a token is minted and the footer prints", () => {
  const f = fixture(matrixAccounts);
  const token = f.token("both-org");
  const footer = f.footer("both-org");

  assert.equal(token.status, 0, token.stderr);
  assert.equal(token.stdout, "github_pat_both-org");
  assert.equal(footer.status, 0, footer.stderr);
  assert.match(footer.stdout, /Generated by Example Agent via .* on `example-host`/);
});

test("credential only: a token is minted, the footer is refused with nothing on stdout", () => {
  const f = fixture(matrixAccounts);
  const token = f.token("cred-org");
  const footer = f.footer("cred-org");

  assert.equal(token.status, 0, token.stderr);
  assert.equal(token.stdout, "github_pat_cred-org");
  assert.equal(footer.status, 2);
  assert.equal(footer.stdout, "");
  assert.match(footer.stderr, /cred-org has no identity block/);
});

test("credential only: --check refuses even when the derived login is bot-shaped, since no signer is declared", () => {
  const f = fixture(matrixAccounts, { actingLogin: "example-agent[bot]" });
  const check = f.check("cred-org");

  assert.equal(check.status, 2);
  assert.match(check.stderr, /cred-org has no identity block/);
});

test("identity only: nothing is minted (exit 3, empty stdout) and the footer prints when gh matches identity.login", () => {
  const f = fixture(matrixAccounts);
  const token = f.token("ident-org");
  const footer = f.footer("ident-org");

  assert.equal(token.status, 3);
  assert.equal(token.stdout, "");
  assert.match(token.stderr, /ident-org has no credential block/);
  assert.equal(footer.status, 0, footer.stderr);
  assert.match(footer.stdout, /Generated by Example Agent/);
});

test("identity only: a derived login that is not identity.login is a mismatch and prints no footer", () => {
  const f = fixture(matrixAccounts, { actingLogin: "someone-else[bot]" });
  const footer = f.footer("ident-org");

  assert.equal(footer.status, 1);
  assert.equal(footer.stdout, "");
  assert.match(footer.stderr, /MISMATCH/);
});

test("an owner absent from accounts gets no token and no footer, even though defaultAccount has both", () => {
  const f = fixture(matrixAccounts);
  const token = f.token("outsider");
  const footer = f.footer("outsider");

  assert.equal(token.status, 1);
  assert.equal(token.stdout, "");
  assert.match(token.stderr, /not allow-listed: outsider/);
  assert.equal(footer.status, 2);
  assert.equal(footer.stdout, "");
  assert.match(footer.stderr, /not allow-listed: outsider/);
});

test("an unresolvable owner routes the token to defaultAccount but never supplies an identity", () => {
  const f = fixture(matrixAccounts);
  const token = f.token();
  const footer = f.footer();
  const check = f.check();

  assert.equal(token.status, 0, token.stderr);
  assert.equal(token.stdout, "github_pat_default-org");
  assert.equal(footer.status, 2);
  assert.equal(footer.stdout, "");
  assert.match(footer.stderr, /No GitHub owner could be resolved/);
  assert.equal(check.status, 2);
});

test("an entry with neither block makes the whole config invalid for both commands", () => {
  const f = fixture((tokenFile) => ({
    "default-org": { accountId: 1, targetType: "organization", credential: pat(tokenFile("default-org")) },
    "empty-org": { accountId: 2, targetType: "organization" }
  }));
  const token = f.token("default-org");
  const footer = f.footer("default-org");

  assert.equal(token.status, 1);
  assert.equal(token.stdout, "");
  assert.match(token.stderr, /empty-org needs a credential block, an identity block, or both/);
  assert.equal(footer.status, 2);
  assert.equal(footer.stdout, "");
});

test("a missing config refuses the footer rather than inventing an identity", () => {
  const f = fixture(matrixAccounts);
  const footer = f.footer("both-org", { IDENTITY_ROUTER_CONFIG: path.join(f.dir, "missing.json") });

  assert.equal(footer.status, 2);
  assert.equal(footer.stdout, "");
});

test("footerHost: absent falls back to the hostname, empty omits the host clause", () => {
  const withHost = (identity) => fixture((tokenFile) => ({
    "default-org": { accountId: 1, targetType: "organization", credential: pat(tokenFile("default-org")), identity }
  }));

  const absent = withHost({ login: "example-agent" }).footer("default-org");
  const empty = withHost({ login: "example-agent", footerHost: "" }).footer("default-org");

  assert.match(absent.stdout, new RegExp(` on \`${os.hostname()}\``));
  assert.doesNotMatch(empty.stdout, / on `/);
});

test("a PAT machine user is accepted only when its plain login is exactly identity.login", () => {
  const accounts = (tokenFile) => ({
    "default-org": {
      accountId: 1,
      targetType: "organization",
      credential: pat(tokenFile("default-org")),
      identity: { login: "example-machine", displayName: "Example Machine", footerHost: "" }
    }
  });

  assert.equal(fixture(accounts, { actingLogin: "example-machine" }).footer("default-org").status, 0);
  // Someone else's account behind the PAT is never blessed by the declaration.
  assert.equal(fixture(accounts, { actingLogin: "third-party" }).footer("default-org").status, 2);
});

test("a plain login with no credential block is refused even when it matches identity.login", () => {
  const f = fixture(() => ({
    "default-org": { accountId: 1, targetType: "organization", identity: { login: "example-user", footerHost: "" } }
  }), { actingLogin: "example-user" });
  const footer = f.footer("default-org");

  assert.equal(footer.status, 2);
  assert.equal(footer.stdout, "");
});

test("kind: human is accepted by --check but never gets an agent footer", () => {
  const f = fixture((tokenFile) => ({
    "default-org": {
      accountId: 1,
      targetType: "organization",
      credential: pat(tokenFile("default-org")),
      identity: { login: "example-user", kind: "human" }
    }
  }), { actingLogin: "example-user" });
  const footer = f.footer("default-org");

  assert.equal(f.check("default-org").status, 0);
  assert.equal(footer.status, 2);
  assert.equal(footer.stdout, "");
  assert.match(footer.stderr, /kind: human is declared/);
});
